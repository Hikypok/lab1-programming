n = int(input("Введите N: "))

# Вывод первых N чисел последовательности Фибоначчи
# Каждое следующее число равно сумме двух предыдущих (a, b = b, a+b)
a, b = 0, 1  # Начальные значения последовательности
print(f"Первые {n} чисел Фибоначчи: ")

for i in range(n):
    print(a, end=" ")
    a, b = b, a + b  # Сдвигаем пару значений на один шаг вперед

print()  # Завершаем строку вывода чисел