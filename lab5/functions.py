import math  # импортируем библиотеку для функций по математике

# Заголовки таблицы значений тригонометрических функций
print(f"{"x":>8} {"sin(x)":>10} {"cos(x)":>10}")
print("-" * 30)

# Цикл от 0 до pi с шагом pi/10 (всего 10 точек)
for i in range(11):
    x = i * math.pi / 10

    # Вычисляем значения функций для текущей точки x
    y1 = math.sin(x)
    y2 = math.cos(x)

    # Выводим строку таблицы с выравниванием по правому краю
    print(f"{x:8.4f} {y1:10.4f} {y2:10.4f}") 
