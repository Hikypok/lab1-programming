import math  # импортируем библиотеку для функций по математике

print(f"{"x":>8} {"sin(x)":>10} {"cos(x)":>10}")  # отформатированные заголовки стобцов
print("-" * 30)

for i in range(11):
    x = i * math.pi / 10
    y1 = math.sin(x)  # вычисление синуса
    y2 = math.cos(x)  # вычисление косинуса
    print(f"{x:8.4f} {y1:10.4f} {y2:10.4f}")